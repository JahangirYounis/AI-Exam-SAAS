using AiExamProctoring.Services.Proctoring;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using System.Text.Json;
using AiExamProctoring.Models;

namespace AiExamProctoring.Areas.Student.Controllers;

public sealed class DeviceReadinessForm
{
    public int AttemptId { get; set; }
    public int SessionAttemptId { get; set; }
    public DateTime CapturedAtUtc { get; set; }
    public bool CameraTrackLive { get; set; }
    public bool MicrophoneTrackLive { get; set; }
    public bool CameraFreshFrame { get; set; }
    public bool MicrophoneAudioFramesAvailable { get; set; }
    public int CameraWidth { get; set; }
    public int CameraHeight { get; set; }
    public string? CameraFrameFingerprint { get; set; }
}

public partial class ExamController
{
    [HttpPost, ValidateAntiForgeryToken]
    [Route("/Student/Exam/DeviceHealth")]
    public async Task<IActionResult> DeviceHealth(int attemptId, int sessionAttemptId, string issue)
    {
        if (StudentId is null) return Unauthorized();
        // This issue is generated by the SERVER watchdog, never by a browser.
        if (!DeviceHealthPolicy.IsIssue(issue) || issue == DeviceHealthPolicy.NetworkIssue)
            return BadRequest(new { ok = false, message = "Invalid device health observation." });
        var result = await _states.HealthAsync(attemptId, sessionAttemptId, StudentId, issue, HttpContext.RequestAborted);
        return result is null ? NotFound() : Json(new {
            ok = true, state = result.State, warning = result.Warning,
            issue = result.Issue, warningCount = result.WarningCount,
            needsReview = result.NeedsReview
        });
    }

    [HttpGet]
    [Route("/Student/Exam/TechnicalHoldStatus")]
    public async Task<IActionResult> TechnicalHoldStatus(int attemptId)
    {
        if (StudentId is null) return Unauthorized();
        var session = await _context.ExamSessionAttempts.AsNoTracking()
            .Where(s => s.AttemptId == attemptId && s.Attempt!.StudentId == StudentId &&
                s.Attempt.Status == AttemptStatus.ProctoringBlocked &&
                s.Status == AttemptStatus.ProctoringBlocked)
            .OrderByDescending(s => s.SessionAttemptId)
            .Select(s => new { s.SessionAttemptId, s.DeviceHealthJson })
            .FirstOrDefaultAsync(HttpContext.RequestAborted);
        if (session is null) return NotFound();
        DeviceHealthEpisode? health = null;
        try { if (session.DeviceHealthJson is not null) health = JsonSerializer.Deserialize<DeviceHealthEpisode>(session.DeviceHealthJson); }
        catch (JsonException) { }
        var technical = health?.IsTechnicalHold == true;
        return Json(new { technical, sessionAttemptId = technical ? session.SessionAttemptId : 0,
            issue = technical ? health!.Issue : null,
            cameraAffected = technical && health!.CameraAffected,
            microphoneAffected = technical && health!.MicrophoneAffected });
    }

    [HttpPost, ValidateAntiForgeryToken]
    [Route("/Student/Exam/DeviceReadiness")]
    public async Task<IActionResult> DeviceReadiness([FromForm] DeviceReadinessForm form)
    {
        if (StudentId is null) return Unauthorized();
        if (form.AttemptId <= 0 || form.SessionAttemptId <= 0)
            return BadRequest(new { ok = false, message = "Invalid attempt." });
        var sample = new DeviceReadinessSample(form.CapturedAtUtc,
            form.CameraTrackLive, form.MicrophoneTrackLive, form.CameraFreshFrame,
            form.MicrophoneAudioFramesAvailable, form.CameraWidth,
            form.CameraHeight, form.CameraFrameFingerprint);
        var result = await _states.RecoverDeviceAsync(form.AttemptId, form.SessionAttemptId,
            StudentId, sample, HttpContext.RequestAborted);
        return Json(new { ok = result.TechnicalHold, recovered = result.Recovered,
            verifiedSamples = result.VerifiedSamples, message = result.Message,
            resumeUrl = result.Recovered ? Url.Action(nameof(Resume), new { attemptId = form.AttemptId }) : null });
    }
}
