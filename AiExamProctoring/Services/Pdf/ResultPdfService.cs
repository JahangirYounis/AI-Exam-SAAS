using AiExamProctoring.Models;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using AiExamProctoring.Services.Pdf;

namespace AiExamProctoring.Services.Pdf
{
    public class ResultPdfService
    {
        public byte[] Generate(ExamResult result, string? examRollNumber = null)
        {
            QuestPDF.Settings.License = LicenseType.Community;

            return Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Margin(30);

                    page.Header()
                        .Text("AI Based Online Examination System")
                        .FontSize(24)
                        .Bold()
                        .AlignCenter();

                    page.Content().Column(col =>
                    {
                        col.Spacing(15);

                        col.Item().Text("Official Examination Result")
                            .FontSize(18)
                            .Bold();

                        col.Item().Table(table =>
                        {
                            table.ColumnsDefinition(c =>
                            {
                                c.ConstantColumn(180);
                                c.RelativeColumn();
                            });

                            void Row(string title, string value)
                            {
                                table.Cell().Border(1).Padding(8).Text(title).Bold();
                                table.Cell().Border(1).Padding(8).Text(value);
                            }

                            //--------------------------------------------------
                            // Calculate Percentage Safely
                            //--------------------------------------------------

                            double percentage = 0;

                            if (result.TotalMarks > 0)
                            {
                                percentage = Math.Round(
                                    (double)(
                                        result.TotalMarksObtained * 100m
                                        / result.TotalMarks
                                    ),
                                    2);
                            }

                            //--------------------------------------------------
                            // Result Information
                            //--------------------------------------------------

                            Row("Candidate Name",
                                result.Attempt!.Student!.FullName);

                            Row("Candidate ID",
                                result.Attempt.Student.CandidateNumber ?? "—");

                            Row("Exam Roll Number",
                                string.IsNullOrWhiteSpace(examRollNumber) ? "—" : examRollNumber);

                            Row("Examination",
                                result.Attempt.Exam!.ExamTitle);

                            Row("Marks Obtained",
                                $"{result.TotalMarksObtained:0.##} / {result.TotalMarks:0.##}");

                            Row("Percentage",
                                $"{percentage:0.##}%");

                            Row("Correct / Wrong / Skipped",
                                $"{result.CorrectAnswers} / {result.WrongAnswers} / {result.SkippedAnswers}");

                            Row("Status",
                                result.IsPassed ? "PASSED" : "FAILED");

                            Row("Result Generated",
                                result.GeneratedDate.ToString("dd MMM yyyy, hh:mm tt"));
                        });
                    });

                    page.Footer()
                        .AlignCenter()
                        .Text(x =>
                        {
                            x.Span("Generated by AI Based Online Examination System");
                        });
                });
            }).GeneratePdf();
        }
    }
}